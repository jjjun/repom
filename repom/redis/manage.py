"""Redis container management commands.

Console scripts:
    uv run redis_generate
    uv run redis_start
    uv run redis_stop
    uv run redis_remove
    uv run redis_rotate_password
"""

from __future__ import annotations

import subprocess
import sys

from repom.config import config
from repom.credentials import reject_default_credential, resolve_password
from repom.docker_compose_safety import (
    format_bound_port,
    format_env_file,
    quote_yaml_string,
    reject_control_characters,
    write_secret_file,
)
from repom.redis.credentials import (
    RedisCredentialRotationPlan,
    build_redis_ping_command,
    rotate_redis_password,
)
from basekit.docker_compose import (
    DockerComposeGenerator,
    DockerService,
    DockerVolume,
)
from basekit.docker_manager import DockerCommandExecutor, DockerManager
from repom.docker_service import (
    ensure_running as ensure_container_service_running,
    remove_service,
    start_service,
    stop_service,
)

COMPOSE_FILENAME = "docker-compose.generated.yml"


class RedisManager(DockerManager):
    """Container manager for the repom Redis service."""

    SERVICE_NAME = "redis"
    INIT_SUBDIR = "redis_init"
    GENERATE_COMMAND = "redis_generate"

    def __init__(self):
        super().__init__(data_path=config.data_path)
        self.config = config

    def get_container_name(self) -> str:
        """Return the configured Redis container name."""

        return self.config.redis.container.get_container_name()

    def wait_for_service(self, max_retries: int = 30) -> None:
        """Wait until redis-cli ping succeeds inside the Redis container.

        The ping is unauthenticated: a password-protected instance answers
        with a NOAUTH error once it is up, which is enough to confirm
        readiness without ever placing the password in the poll's argv.
        """

        container_name = self.get_container_name()
        command = build_redis_ping_command(container_name=container_name)

        def check_redis_ready():
            try:
                result = subprocess.run(
                    command,
                    capture_output=True,
                    text=True,
                    timeout=2,
                    check=False,
                )
                if result.returncode == 0 and "PONG" in result.stdout:
                    return True
                return "NOAUTH" in result.stdout or "NOAUTH" in result.stderr
            except Exception:
                return False

        DockerCommandExecutor.wait_for_readiness(
            check_redis_ready,
            max_retries=max_retries,
            service_name="Redis",
        )

    def print_connection_info(self) -> None:
        """Print local Redis connection details."""

        print()
        print("Redis Connection:")
        print("  Host: 127.0.0.1")
        print(f"  Port: {self.config.redis.port}")
        if self.config.redis.password:
            print("  Auth: enabled")
            print(f"  CLI: REDISCLI_AUTH=*** redis-cli -p {self.config.redis.port}")
        else:
            print("  Auth: disabled")
            print(f"  CLI: redis-cli -p {self.config.redis.port}")
        print()


def generate_redis_conf(password: str | None = None) -> str:
    """Generate redis.conf content from the active config.

    This file is bind-mounted into the container, so it must never carry the
    password: ``generate_docker_compose()`` passes it to the container via
    the service environment and starts Redis with ``--requirepass`` instead
    of writing it here.
    """

    redis_password = config.redis.password if password is None else password
    reject_default_credential(redis_password, env_var="REDIS_PASSWORD")
    reject_control_characters(redis_password, field_name="redis.password")

    return """# Redis Configuration (auto-generated by repom)
#
# Do not edit manually - modify config in repom/config.py instead

# Network
protected-mode yes

# Database
databases 16

# Persistence
appendonly yes
appendfsync everysec

# Snapshots
save 900 1
save 300 10
save 60 10000

# Memory
maxmemory 256mb
maxmemory-policy allkeys-lru

# Logging
loglevel notice
"""


def generate_docker_compose() -> DockerComposeGenerator:
    """Generate a compose model for Redis."""

    manager = RedisManager()
    container = config.redis.container
    redis_port = config.redis.port
    redis_password = config.redis.password
    reject_default_credential(redis_password, env_var="REDIS_PASSWORD")
    reject_control_characters(redis_password, field_name="redis.password")
    container_name = reject_control_characters(
        container.get_container_name(), field_name="redis.container.container_name"
    )
    volume_name = reject_control_characters(
        container.get_volume_name(), field_name="redis.container.volume_name"
    )
    image = container.image
    init_dir = manager.get_init_dir()

    redis_service = DockerService(
        name="redis",
        image=image,
        container_name=container_name,
        environment={"REDIS_PASSWORD": quote_yaml_string("${REDIS_PASSWORD}")},
        ports=[format_bound_port(redis_port, 6379, expose_to_lan=container.expose_to_lan)],
        volumes=[
            f"{volume_name}:/data",
            f"{init_dir.absolute()}/redis.conf:/usr/local/etc/redis/redis.conf",
        ],
        command=(
            "sh -c 'exec redis-server /usr/local/etc/redis/redis.conf "
            "--requirepass \"$$REDIS_PASSWORD\"'"
        ),
        healthcheck={
            "test": '["CMD-SHELL", "redis-cli -a \\"$$REDIS_PASSWORD\\" ping"]',
            "interval": "5s",
            "timeout": "5s",
            "retries": 5,
        },
    )

    generator = DockerComposeGenerator()
    generator.add_service(redis_service)
    generator.add_volume(DockerVolume(name=volume_name))

    return generator


def generate():
    """Write Redis compose and redis.conf files."""

    manager = RedisManager()
    redis_conf = generate_redis_conf()
    init_dir = manager.get_init_dir()
    (init_dir / "redis.conf").write_text(redis_conf, encoding="utf-8")

    generator = generate_docker_compose()
    compose_dir = manager.get_compose_dir()
    output_path = compose_dir / COMPOSE_FILENAME
    generator.write_to_file(output_path)

    write_secret_file(
        compose_dir / ".env",
        format_env_file({"REDIS_PASSWORD": config.redis.password}),
    )

    print(f"Generated: {output_path}")
    print(f"   Config: {init_dir / 'redis.conf'}")
    print("\nRedis Service:")
    print(f"   Container: {config.redis.container.get_container_name()}")
    print(f"   Port: {config.redis.port}")
    print(f"   Volume: {config.redis.container.get_volume_name()}")
    print("   Auth: enabled")


def start():
    """Generate files and start Redis."""

    start_service(RedisManager, generate)


def stop():
    """Stop Redis."""

    stop_service(RedisManager)


def ensure_running(*, timeout_seconds: int = 30) -> None:
    """Ensure Redis is running for application lifespan hooks.

    The compose files are generated and the Redis container is started when it
    is not already running.

    Args:
        timeout_seconds: Number of seconds to wait for readiness.

    Raises:
        RuntimeError: The container runtime is unavailable or Redis fails to start.
    """

    ensure_container_service_running(
        RedisManager,
        {"redis": config.redis.container.get_container_name()},
        generate,
        "Redis",
        timeout_seconds,
    )


def remove():
    """Remove Redis containers and volumes."""

    remove_service(RedisManager)


def rotate_password(
    new_password: str | None = None,
    *,
    old_password: str | None = None,
    allow_config_password: bool = False,
    dry_run: bool = True,
):
    """Apply a new Redis password to the running instance and persisted config."""

    if new_password is None:
        if not allow_config_password:
            raise ValueError("new_password is required for Redis rotation")
        password = config.redis.password
    else:
        password = new_password
    if not password:
        raise ValueError("new_password must not be empty for Redis rotation")

    result = rotate_redis_password(
        plan=RedisCredentialRotationPlan.from_config(
            old_password=old_password,
            new_password=password,
        ),
        dry_run=dry_run,
    )
    if not dry_run:
        config.redis.password = password
        generate()
    for line in (result.masked_command, result.masked_input.strip()):
        print(line)
    return result


def main_rotate_password():
    """Console entry point for Redis password rotation."""

    import argparse

    parser = argparse.ArgumentParser(
        description="Rotate the password for a running repom Redis container.",
        epilog=(
            "Update the configured password holder before rotating Redis. "
            "--new-password and --old-password expose values in process arguments; "
            "use the stdin options or TTY prompts instead."
        ),
    )
    new_password_group = parser.add_mutually_exclusive_group()
    new_password_group.add_argument(
        "--new-password",
        default=None,
        help="New password (visible in process arguments).",
    )
    new_password_group.add_argument(
        "--new-password-stdin",
        action="store_true",
        help=(
            "Read the new password from one line of standard input. When more "
            "than one stdin option is used, the new password is read first."
        ),
    )
    new_password_group.add_argument(
        "--allow-config-password",
        action="store_true",
        help="Use config.redis.password as the new password.",
    )
    old_password_group = parser.add_mutually_exclusive_group()
    old_password_group.add_argument(
        "--old-password",
        default=None,
        help="Current password (visible in process arguments).",
    )
    old_password_group.add_argument(
        "--old-password-stdin",
        action="store_true",
        help=(
            "Read the current password from one line of standard input. When more "
            "than one stdin option is used, the new password is read first."
        ),
    )
    parser.add_argument(
        "--execute",
        action="store_true",
        help="Execute the rotation. Without this flag, only a dry-run is printed.",
    )
    args = parser.parse_args()
    new_password = resolve_password(
        password=args.new_password,
        read_stdin=args.new_password_stdin,
        allow_config_password=args.allow_config_password,
        config_password=config.redis.password,
        prompt="New Redis password: ",
        option_name="--new-password",
    )
    old_password = args.old_password
    if args.old_password_stdin:
        old_password = resolve_password(
            password=None,
            read_stdin=True,
            prompt="Current Redis password: ",
            option_name="--old-password",
            allow_empty=True,
        )
    elif old_password is None and sys.stdin.isatty():
        old_password = resolve_password(
            password=None,
            read_stdin=False,
            prompt="Current Redis password (leave blank if unset): ",
            option_name="--old-password",
            allow_empty=True,
        )

    rotate_password(
        new_password=new_password,
        old_password=old_password or None,
        dry_run=not args.execute,
    )
